import { test, expect } from '@playwright/test';

const PAGE = '/TikTokStudio_prototype.html';
const phone = (page) => page.locator('#phone-screen');
const act = (page, a) => page.locator(`#phone-screen [data-act="${a}"]:visible`);
async function tap(page, a, i) { const l = act(page, a); await (i == null ? l.last() : l.nth(i)).click(); await page.waitForTimeout(450); }
async function shot(page, name) { await page.waitForTimeout(250); await phone(page).screenshot({ path: `qa/${name}.jpg`, type: 'jpeg', quality: 78 }); }
async function boot(page, market = 'us') {
  await page.goto(PAGE);
  if (market === 'store') await page.getByLabel(/旧版美国/).check(); // V4 默认 = 美国 2026-11-22 真机录屏
  await tap(page, 'welcome-continue');
  await page.waitForTimeout(900);
}
// 死链检查：手机里可见的 button / [role=tab] 必须带 data-act
async function deadCheck(page, where) {
  const bad = await page.evaluate(() => {
    const root = document.getElementById('phone-screen');
    return [...root.querySelectorAll('button, [role="tab"]')]
      .filter((el) => el.offsetParent !== null && !el.closest('[data-act]') && !el.closest('.semi-scrolllist'))
      .map((el) => (el.textContent || el.getAttribute('aria-label') || el.className).trim().slice(0, 40));
  });
  if (bad.length) console.log(`[deadCheck] ${where}:`, bad);
  return bad;
}
async function dragChart(page, from = 0.3, to = 0.8) {
  // 2026-11-26：Overview 顶部多了评分卡，趋势图在首屏以下，先滚到可见再拖（否则会拖到 Tab 栏上）
  await page.locator('#phone-screen .trend svg:visible').first().scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
  const box = await page.locator('#phone-screen .trend svg:visible').first().boundingBox();
  const y = box.y + box.height * 0.5;
  await page.mouse.move(box.x + box.width * from, y);
  await page.mouse.down();
  for (let i = 0; i <= 8; i++) await page.mouse.move(box.x + box.width * (from + ((to - from) * i) / 8), y);
  await page.mouse.up();
}
async function edgeSwipeBack(page) {
  const box = await phone(page).boundingBox();
  const y = box.y + box.height / 2;
  await page.mouse.move(box.x + 6, y);
  await page.mouse.down();
  for (let i = 1; i <= 12; i++) await page.mouse.move(box.x + 6 + i * 22, y, { steps: 1 });
  await page.mouse.up();
  await page.waitForTimeout(600);
}

